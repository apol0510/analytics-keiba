/**
 * thresholds.js — 無料「レースの見どころ」タグ判定のしきい値（**単一源・凍結値**）
 *
 * ── 何のための値か ──────────────────────────────────────────────
 * 無料第 2 層（全レース一覧＋各レースの短い見どころ）で出す**絶対タグ**の境界。
 * 「距離替わり多め」等の意味を**日によって変えない**ため、当日の分布ではなく
 * **JRA / 南関それぞれのカテゴリ全体の分布**から求めた固定値を使う。
 * （当日の中での相対順位は別レイヤー＝`dailyHighlights` で扱う。混同しないこと）
 *
 * ── 値の出どころ（2026-08-19 実測）────────────────────────────
 * 「通常タグ判定に進めるレース」＝ 全頭照合できて過去走があるレースだけを母集団とし、
 * 各指標の **p20 / p80** を採った。
 *   南関: 660 レース（`horseStats/nankan` が揃う 2026-06〜08）
 *   JRA : 753 レース（`horseHistories/jra` と全頭照合できたもの / 2026-05〜08）
 * JRA 側は `(地)`/`(外)` 接頭辞の照合漏れを修正した**あとの**データで算出している
 * （修正前の値は初コース・乗り替わりが系統的に小さく出るため使ってはいけない）。
 *
 * ── なぜ p20/p80 か（p85/p90 と比較した実測）──────────────────
 * しきい値を上げてもタグが減るだけで**安定性は改善しなかった**
 * （例 南関「近走比較」: p80 で −1 頭により判定が変わる率 51% → p90 で 81%）。
 * 7〜18 頭という母数に対する帯判定の感度は本質的なもので、閾値では解けない。
 * よってタグ数を確保できる p20/p80 を採る。
 *
 * ── なぜ MIN_HORSES = 3 か ────────────────────────────────────
 * 実測で「1〜2 頭で成立してしまうタグ」は**南関の初コースだけ**だった
 * （p80 タグ 134 件のうち 74 件＝55% が 2 頭以下、最小 1 頭）。
 * 他の次元は該当頭数の最小が 3〜4 頭で、最低頭数を課しても件数が変わらない。
 * 3 頭を課すと南関初コースは 134→60 件へ絞られ、
 * **−1 頭で判定が変わる率が 57% → 3%** に落ちる。全次元共通の 1 定数で足りる。
 *
 * ── 変更するときの手順 ────────────────────────────────────────
 * この値を変えると全レースの表示が変わる。必ず
 *   1. 同じ母集団定義（全頭照合 × 過去走あり）で再測定する
 *   2. `raceViewpoints.test.mjs` の期待値を更新する
 *   3. `docs/progress.md` に測定日・母数・新旧の値を残す
 * を通すこと。**当日の分布から動的に決める方式へ戻してはいけない**（意味が日替わりになる）。
 */

/** タグを立てるのに必要な最低該当頭数（全次元共通）。 */
export const MIN_HORSES = 3;

/**
 * カテゴリ別のしきい値。`[p20, p80]`（割合）。
 * `dist` / `first` / `jchg` は上側のみ、`comp` は上下両方を使う。
 */
export const THRESHOLDS = Object.freeze({
  nankan: Object.freeze({
    dist:  Object.freeze([0.14, 0.57]),
    first: Object.freeze([0.00, 0.15]),
    jchg:  Object.freeze([0.25, 0.56]),
    comp:  Object.freeze([0.33, 0.78]),
  }),
  jra: Object.freeze({
    dist:  Object.freeze([0.19, 0.62]),
    first: Object.freeze([0.25, 0.79]),
    jchg:  Object.freeze([0.44, 0.79]),
    comp:  Object.freeze([0.00, 0.43]),
  }),
});

/** 距離が「替わった」と見なす差（m）。 */
export const DISTANCE_CHANGE_METERS = 200;

/** 近走の参照本数（各カテゴリの源から先頭 N 走）。 */
export const RECENT_RACES_WINDOW = 5;

/**
 * JRA で通常タグ判定に進める照合率。**全頭照合のみ**を第一候補とする。
 * 実測（852 レース）で全頭照合が 98.6% あり、しきい値を下げる動機が無い。
 * 南関は馬番結合のため常に 1.0。
 */
export const REQUIRED_COVERAGE = 1.0;

export default { MIN_HORSES, THRESHOLDS, DISTANCE_CHANGE_METERS, RECENT_RACES_WINDOW, REQUIRED_COVERAGE };
