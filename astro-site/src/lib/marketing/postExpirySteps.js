/**
 * postExpirySteps.js — 無料体験**終了後**フェーズの 18 通（文面の単一源）
 *
 * ── なぜ別フェーズか ──────────────────────────────────────────
 * 24 通の接点を作りたいが、**無料体験は 30 日で終わる**。
 * 最短 3 日間隔 + 無反応での間隔延長では、体験中に入るのは 6 通前後。
 * 体験中フェーズ（`light-trial-to-premium-sequence`）は
 * 「権利が有効であること」を前提に書いてあるので、期限が切れた相手へ送ると**嘘になる**。
 *
 * そこで 7 通目以降を**別キャンペーン**（`light-trial-post-expiry-sequence`）に分け、
 * 「体験は終わった」という事実の上に立つ文面だけを置く。
 * 累計は 体験中 6 通 + 終了後 18 通 = **24 接点**（`journeyModel.js` が通し番号を持つ）。
 *
 * ── 絶対に書かないこと（事実と違う表現）──────────────────────
 * - 「無料体験中です」「まだ無料でご利用いただけます」
 * - 「無料期間の残り」「期限までに」など、**終わった期間を現在形で扱う表現**
 * - `{{grantExpiry}}`（体験の終了日の差し込み。終了後の案内では使わない）
 *
 * ── 書くときの禁止事項（体験中フェーズと同じ）───────────────────
 * - 的中・利益の**保証**、「必ず」「絶対」「確実に」
 * - **架空の実績・数値**（実績はページへ誘導し、メールに書き写さない）
 * - 「今だけ」「残りわずか」の煽り
 * - 価格の直書き（`/pricing/` が正本）
 *
 * ⚠️ **本番送信はしない。** 管理画面の `action=preview` で 1 通ずつ確認できる。
 */

